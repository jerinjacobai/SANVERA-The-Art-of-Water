// Query and helper functions
export const getProductById = (id: string): SanveraProduct | undefined => {
  return SANVERA_CATALOG.find((p) => p.id === id);
};

export const getProductsByCategory = (category: ProductCategory): SanveraProduct[] => {
  return SANVERA_CATALOG.filter((p) => p.category === category);
};

export const getFeaturedCatalogProducts = (): SanveraProduct[] => {
  return SANVERA_CATALOG.filter((p) => p.featured);
};

export const getShowroomZoneProducts = (zoneIndex: number): SanveraProduct[] => {
  return SANVERA_CATALOG.filter((p) => p.spatialZone === zoneIndex);
};

export const searchCatalog = (query: string): SanveraProduct[] => {
  const q = query.toLowerCase().trim();
  if (!q) return [];
  return SANVERA_CATALOG.filter((p) =>
    p.name.toLowerCase().includes(q) ||
    p.family.toLowerCase().includes(q) ||
    p.sku.toLowerCase().includes(q) ||
    p.description.toLowerCase().includes(q) ||
    p.tags.some((t) => t.toLowerCase().includes(q))
  );
};
